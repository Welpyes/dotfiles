def gen_foot(c: dict) -> str:
    lines = [f"# {GEN_NOTE}", "", "[colors-dark]", "alpha=1", "alpha-mode=default"]
    lines.append(f"background={c['bg']}")
    lines.append(f"foreground={c['fg']}")
    lines.append(f"regular0={c['surface']}")   # black
    lines.append(f"regular1={c['error']}")     # red
    lines.append(f"regular2={c['success']}")   # green
    lines.append(f"regular3={c['warn']}")      # yellow
    lines.append(f"regular4={c['accent']}")    # blue
    lines.append(f"regular5={c['info']}")      # magenta/purple
    lines.append(f"regular6={c['teal']}")      # cyan
    lines.append(f"regular7={c['fg']}")        # white
    lines.append(f"bright0={c['fg_dim']}")     # bright black
    lines.append(f"bright1={c['error_dark']}")
    lines.append(f"bright2={c['success_dark']}")
    lines.append(f"bright3={c['warn_dark']}")
    lines.append(f"bright4={c['accent_dark']}")
    lines.append(f"bright5={c['info_dark']}")
    lines.append(f"bright6={c['teal_dark']}")
    lines.append(f"bright7=FFFFFF")            # bright white
    return "\n".join(lines) + "\n"


def gen_sway(c: dict) -> str:
    lines = [
        f"# {GEN_NOTE}",
        "",
        f"client.focused          #{c['border']} #{c['surface']} #{c['fg']} #{c['accent']} #{c['border']}",
        f"client.unfocused        #{c['surface_alt']} #{c['surface_alt']} #{c['fg_dim']} #{c['fg_dim']} #{c['surface_alt']}",
        f"client.focused_inactive #{c['surface_alt']} #{c['surface']} #{c['fg_dim']} #{c['fg_dim']} #{c['surface_alt']}",
        "",
    ]
    return "\n".join(lines)


def gen_zsh(c: dict) -> str:
    lines = [f"# {GEN_NOTE}", ""]
    for role in sorted(c):
        lines.append(f'export COLOURS_{role.upper()}="#{c[role]}"')
    return "\n".join(lines) + "\n"


def gen_rofi(c: dict) -> str:
    lines = [
        f"/* {GEN_NOTE} */",
        "* {",
        f"  bg: #{c['bg']};",
        f"  bg-alt: #{c['surface']};",
        f"  fg: #{c['fg']};",
        f"  fg-alt: #{c['fg_dim']};",
        f"  red: #{c['error']};",
        f"  green: #{c['success']};",
        f"  yellow: #{c['warn']};",
        f"  blue: #{c['accent']};",
        f"  purple: #{c['info']};",
        f"  cyan: #{c['teal']};",
        f"  grey: #{c['border']};",
        '  background-color: transparent;',
        '  font: "Ioskeley Mono Semibold 12";',
        "}",
        "",
    ]
    return "\n".join(lines)


def gen_posh(c: dict) -> str:
    lines = [f"# {GEN_NOTE}", "", "[colors]"]
    for role in sorted(c):
        lines.append(f'{role} = "#{c[role]}"')
    return "\n".join(lines) + "\n"


def gen_nvim(c: dict) -> str:
    roles = ",\n  ".join(f'{role} = "#{c[role]}"' for role in sorted(c))
    hl_calls = []
    for group, opts in _NVIM_HIGHLIGHTS.items():
        resolved = []
        for k, v in opts.items():
            if k == "link":
                resolved.append(f"{k} = {v!r}")
            elif isinstance(v, bool):
                resolved.append(f"{k} = {v}")
            else:
                resolved.append(f'{k} = "#{c[v]}"')
        args = ", ".join(resolved)
        hl_calls.append(f'  hl("{group}", {{{args}}})')
    return f"""\
-- {GEN_NOTE}
local M = {{}}

M.colors = {{
  {roles}
}}

local function hl(group, opts)
  vim.api.nvim_set_hl(0, group, opts)
end

function M.setup()
  vim.o.background = "light"
  vim.o.termguicolors = true
  if vim.g.colors_name then
    vim.cmd("hi clear")
  end
  vim.g.colors_name = "sweet-blush"
  local c = M.colors
{chr(10).join(hl_calls)}
end

return M
"""


