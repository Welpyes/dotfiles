#!/usr/bin/env python3
"""gen-colors.py — centralized colourscheme generator for dotfiles.

Single source of truth: pallete.json.
Generates colourscheme.* files into dotfiles/dot-config/colours/ (stowed to
$HOME/.config/colours/) and wires them into host configs that support a native
include/source mechanism. Configs without includes (oh-my-posh toml, rofi
theme-generated.rasi) are rewritten faithfully from the palette.

Usage:
  ./scripts/gen-colors.py generate   # write colours/* partials only
  ./scripts/gen-colors.py apply      # generate + wire into host configs
  ./scripts/gen-colors.py check      # verify palette + generated files agree

In scope: oh-my-posh, zsh, rofi, sway, foot. Neovim and everything else untouched.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PALETTE = REPO_ROOT / "pallete.json"
COLOURS_DIR = REPO_ROOT / "dotfiles" / "dot-config" / "colours"
HOME = Path(__file__).resolve().anchor and Path.home()
INSTALL_DIR = HOME / ".config" / "colours"

# semantic role -> palette key. palette.json remains the single source of truth.
ROLES = {
    "bg": "background",
    "fg": "foreground",
    "fg_dim": "muted",
    "fg_dark": "foreground_dark",
    "surface": "surface",
    "surface_alt": "surface_alt",
    "border": "border",
    "accent": "blue",
    "accent_light": "blue_light",
    "accent_dark": "blue_dark",
    "success": "green",
    "success_light": "green_light",
    "success_dark": "green_dark",
    "warn": "yellow",
    "warn_light": "yellow_light",
    "warn_dark": "yellow_dark",
    "error": "red",
    "error_light": "red_light",
    "error_dark": "red_dark",
    "info": "purple",
    "info_light": "purple_light",
    "info_dark": "purple_dark",
    "pink": "pink",
    "pink_light": "pink_light",
    "pink_dark": "pink_dark",
    "orange": "orange",
    "orange_light": "orange_light",
    "orange_dark": "orange_dark",
    "teal": "teal",
    "teal_light": "teal_light",
    "teal_dark": "teal_dark",
}

GEN_NOTE = "Generated by scripts/gen-colors.py from pallete.json — DO NOT EDIT BY HAND"
START = f"# >>> colours >>> ({GEN_NOTE})"
END = f"# <<< colours <<<"


def load_palette() -> dict:
    with open(PALETTE, encoding="utf-8") as fh:
        return json.load(fh)


def hex_of(key: str) -> str:
    return load_palette()[key].lstrip("#")


def colours() -> dict:
    return {role: hex_of(key) for role, key in ROLES.items()}


# --------------------------------------------------------------------------- #
# generators for colours/* partials
# --------------------------------------------------------------------------- #

def gen_foot(c: dict) -> str:
    lines = [f"# {GEN_NOTE}", "", "[colors-dark]", "alpha=1", "alpha-mode=default"]
    lines.append(f"background={c['bg']}")
    lines.append(f"foreground={c['fg']}")
    lines.append(f"regular0={c['surface']}")   # black
    lines.append(f"regular1={c['error']}")     # red
    lines.append(f"regular2={c['success']}")   # green
    lines.append(f"regular3={c['warn']}")      # yellow
    lines.append(f"regular4={c['accent']}")    # blue
    lines.append(f"regular5={c['info']}")      # magenta/purple
    lines.append(f"regular6={c['teal']}")      # cyan
    lines.append(f"regular7={c['fg']}")        # white
    lines.append(f"bright0={c['fg_dim']}")     # bright black
    lines.append(f"bright1={c['error_dark']}")
    lines.append(f"bright2={c['success_dark']}")
    lines.append(f"bright3={c['warn_dark']}")
    lines.append(f"bright4={c['accent_dark']}")
    lines.append(f"bright5={c['info_dark']}")
    lines.append(f"bright6={c['teal_dark']}")
    lines.append(f"bright7=FFFFFF")            # bright white
    return "\n".join(lines) + "\n"


def gen_sway(c: dict) -> str:
    lines = [
        f"# {GEN_NOTE}",
        "",
        f"client.focused          #{c['border']} #{c['surface']} #{c['fg']} #{c['accent']} #{c['border']}",
        f"client.unfocused        #{c['surface_alt']} #{c['surface_alt']} #{c['fg_dim']} #{c['fg_dim']} #{c['surface_alt']}",
        f"client.focused_inactive #{c['surface_alt']} #{c['surface']} #{c['fg_dim']} #{c['fg_dim']} #{c['surface_alt']}",
        "",
    ]
    return "\n".join(lines)


def gen_zsh(c: dict) -> str:
    lines = [f"# {GEN_NOTE}", ""]
    for role in sorted(c):
        lines.append(f'export COLOURS_{role.upper()}="#{c[role]}"')
    return "\n".join(lines) + "\n"


def gen_rofi(c: dict) -> str:
    lines = [
        f"/* {GEN_NOTE} */",
        "* {",
        f"  bg: #{c['bg']};",
        f"  bg-alt: #{c['surface']};",
        f"  fg: #{c['fg']};",
        f"  fg-alt: #{c['fg_dim']};",
        f"  red: #{c['error']};",
        f"  green: #{c['success']};",
        f"  yellow: #{c['warn']};",
        f"  blue: #{c['accent']};",
        f"  purple: #{c['info']};",
        f"  cyan: #{c['teal']};",
        f"  grey: #{c['border']};",
        '  background-color: transparent;',
        '  font: "Ioskeley Mono Semibold 12";',
        "}",
        "",
    ]
    return "\n".join(lines)


def gen_posh(c: dict) -> str:
    lines = [f"# {GEN_NOTE}", "", "[colors]"]
    for role in sorted(c):
        lines.append(f'{role} = "#{c[role]}"')
    return "\n".join(lines) + "\n"


GENERATORS = {
    "foot": ("foot.ini", gen_foot),
    "sway": ("sway.conf", gen_sway),
    "zsh": ("zsh.sh", gen_zsh),
    "rofi": ("rofi.rasi", gen_rofi),
    "posh": ("posh.toml", gen_posh),
}

HOSTS = {
    "foot": REPO_ROOT / "dotfiles" / "dot-config" / "foot" / "foot.ini",
    "sway": REPO_ROOT / "dotfiles" / "dot-config" / "sway" / "config",
    "zsh": REPO_ROOT / "dotfiles" / "dot-config" / "zsh" / "env.zsh",
    "posh": REPO_ROOT / "dotfiles" / "dot-config" / "oh-my-posh" / "zen.toml",
    "rofi": REPO_ROOT / "dotfiles" / "dot-config" / "rofi" / "theme-generated.rasi",
}


# --------------------------------------------------------------------------- #
# file writing
# --------------------------------------------------------------------------- #

def generate() -> None:
    COLOURS_DIR.mkdir(parents=True, exist_ok=True)
    c = colours()
    for name, (fname, fn) in GENERATORS.items():
        out = COLOURS_DIR / fname
        out.write_text(fn(c), encoding="utf-8")
        print(f"wrote {out}")


# --------------------------------------------------------------------------- #
# host-config wiring
# --------------------------------------------------------------------------- #

def _has_marker(text: str) -> bool:
    return START in text


def _replace_between(text: str, block: str) -> str:
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)
    replacement = f"{START}\n{block.rstrip()}\n{END}"
    if pattern.search(text):
        return pattern.sub(replacement, text)
    return text


def wire_foot(text: str, c: dict) -> str:
    include = f'include = {INSTALL_DIR / "foot.ini"}'
    block = f"{include}\n"
    # replace the [colors-dark] section body with just the include
    pattern = re.compile(r"\[colors-dark\](.*?)(?=\n\[|\Z)", re.DOTALL)
    new_section = f"[colors-dark]\n{block}"
    if pattern.search(text):
        return pattern.sub(new_section, text)
    # no [colors-dark] section: append at top
    return new_section + "\n" + text


def wire_sway(text: str, c: dict) -> str:
    # drop hardcoded client.* colour lines (they live in colours/sway.conf now)
    text = re.sub(r"^\s*client\.(focused|unfocused|focused_inactive)\s.*\n?", "", text, flags=re.M)
    block = f'include {INSTALL_DIR / "sway.conf"}\n'
    if _has_marker(text):
        return _replace_between(text, block)
    return f"{START}\n{block}{END}\n\n{text}"


def wire_zsh(text: str, c: dict) -> str:
    block = f'source "{INSTALL_DIR / "zsh.sh"}"\n'
    if _has_marker(text):
        return _replace_between(text, block)
    return text.rstrip() + f"\n\n{START}\n{block}{END}\n"


def wire_posh(text: str, c: dict) -> str:
    # oh-my-posh has no include: rewrite zen.toml faithfully from palette.
    return gen_posh_zen(c)


def gen_posh_zen(c: dict) -> str:
    err = c["error"]
    ok = c["info"]
    accent = c["accent"]
    warn = c["warn"]
    teal = c["teal"]
    git_tmpl = (
        " {{ .HEAD }}{{ if or (.Working.Changed) (.Staging.Changed) }}*{{ end }} <#"
        + teal
        + "{{ if gt .Behind 0 }}⇣{{ end }}{{ if gt .Ahead 0 }}⇡{{ end }}</>"
    )
    template = """\
# __NOTE__
console_title_template = '{{ .Shell }} in {{ .Folder }}'
version = 3
final_space = true

[secondary_prompt]
  template = '❯❯ '
  foreground = '__OK__'
  background = 'transparent'

[transient_prompt]
  template = '❯ '
  background = 'transparent'
  foreground_templates = ['{{if gt .Code 0}}__ERR__{{end}}', '{{if eq .Code 0}}__OK__{{end}}']

[[blocks]]
  type = 'prompt'
  alignment = 'left'
  newline = true

  [[blocks.segments]]
    template = ' {{ .Path }}'
    foreground = '__ACCENT__'
    background = 'transparent'
    type = 'path'
    style = 'plain'

    [blocks.segments.properties]
      cache_duration = 'none'
      style = 'full'

  [[blocks.segments]]
    template = '__GIT__'
    foreground = '__WARN__'
    background = 'transparent'
    type = 'git'
    style = 'plain'

    [blocks.segments.properties]
      branch_icon = ''
      cache_duration = 'none'
      commit_icon = '@'
      fetch_status = true

[[blocks]]
  type = 'rprompt'
  overflow = 'hidden'

  [[blocks.segments]]
    template = '{{ .FormattedMs }}'
    foreground = '__WARN__'
    background = 'transparent'
    type = 'executiontime'
    style = 'plain'

    [blocks.segments.properties]
      cache_duration = 'none'
      threshold = 5000

[[blocks]]
  type = 'prompt'
  alignment = 'left'
  newline = true

  [[blocks.segments]]
    template = '  ❯'
    background = 'transparent'
    type = 'text'
    style = 'plain'
    foreground_templates = ['{{if gt .Code 0}}__ERR__{{end}}', '{{if eq .Code 0}}__OK__{{end}}']

    [blocks.segments.properties]
      cache_duration = 'none'
"""
    return (
        template.replace("__NOTE__", GEN_NOTE)
        .replace("__ERR__", "#" + err)
        .replace("__OK__", "#" + ok)
        .replace("__ACCENT__", "#" + accent)
        .replace("__WARN__", "#" + warn)
        .replace("__TEAL__", "#" + teal)
        .replace("__GIT__", git_tmpl)
    )


def wire_rofi(text: str, c: dict) -> str:
    # rofi themes support @import; theme-generated.rasi now imports colours/rofi.rasi
    rel = (INSTALL_DIR / "rofi.rasi").relative_to(HOME / ".config")
    # theme-generated.rasi lives in ~/.config/rofi/; colours is one dir up.
    import_path = f'../colours/rofi.rasi'
    return f"""\
/* {GEN_NOTE} */
@import "{import_path}"
"""


WIRE = {
    "foot": wire_foot,
    "sway": wire_sway,
    "zsh": wire_zsh,
    "posh": wire_posh,
    "rofi": wire_rofi,
}


def apply_() -> None:
    generate()
    c = colours()
    for name, path in HOSTS.items():
        text = path.read_text(encoding="utf-8")
        new = WIRE[name](text, c)
        if new != text:
            path.write_text(new, encoding="utf-8")
            print(f"wired {path}")
        else:
            print(f"unchanged {path}")


def check() -> None:
    c = colours()
    problems = []
    if not PALETTE.exists():
        problems.append(f"missing {PALETTE}")
    for name, (fname, _) in GENERATORS.items():
        out = COLOURS_DIR / fname
        if not out.exists():
            problems.append(f"missing {out}")
    for name, path in HOSTS.items():
        if not path.exists():
            problems.append(f"missing host {path}")
    if problems:
        for p in problems:
            print(f"! {p}")
        sys.exit(1)
    print("ok: palette and colours in sync")


def main() -> None:
    if len(sys.argv) != 2 or sys.argv[1] not in {"generate", "apply", "check"}:
        print("usage: gen-colors.py [generate|apply|check]")
        sys.exit(2)
    cmd = sys.argv[1]
    if cmd == "generate":
        generate()
    elif cmd == "apply":
        apply_()
    else:
        check()


if __name__ == "__main__":
    main()
