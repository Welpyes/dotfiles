#!/usr/bin/env python3
"""gen-colors.py — centralized colourscheme generator for dotfiles.

Single source of truth: pallete.json.
Generates colourscheme.* files into dotfiles/dot-config/colours/ (stowed to
$HOME/.config/colours/) and wires them into host configs that support a native
include/source mechanism. Configs without includes (oh-my-posh toml, rofi
theme-generated.rasi) are rewritten faithfully from the palette.

Usage:
  ./scripts/gen-colors.py generate   # write colours/* partials only
  ./scripts/gen-colors.py apply      # generate + wire into host configs
  ./scripts/gen-colors.py check      # verify palette + generated files agree

In scope: oh-my-posh, zsh, rofi, sway, foot. Neovim and everything else untouched.
"""

