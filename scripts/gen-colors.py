def load_palette() -> dict:
    with open(PALETTE, encoding="utf-8") as fh:
        return json.load(fh)


def hex_of(key: str) -> str:
    return load_palette()[key].lstrip("#")


def colours() -> dict:
    c = {role: hex_of(key) for role, key in ROLES.items()}
    # expose palette keys directly too (e.g. muted -> c["muted"])
    palette = load_palette()
    for key in palette:
        if key not in c:
            c[key] = hex_of(key)
    return c


