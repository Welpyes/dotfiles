def apply_() -> None:
    generate()
    c = colours()
    for name, path in HOSTS.items():
        text = path.read_text(encoding="utf-8")
        new = WIRE[name](text, c)
        if new != text:
            path.write_text(new, encoding="utf-8")
            print(f"wired {path}")
        else:
            print(f"unchanged {path}")


def check() -> None:
    c = colours()
    problems = []
    if not PALETTE.exists():
        problems.append(f"missing {PALETTE}")
    for name, (fname, fn) in GENERATORS.items():
        result = fn(c)
        if isinstance(result, dict):
            for rel_path in result:
                out = THEME_DIR / rel_path
                if not out.exists():
                    problems.append(f"missing {out}")
        else:
            out = COLOURS_DIR / fname
            if not out.exists():
                problems.append(f"missing {out}")
    for name, path in HOSTS.items():
        if not path.exists():
            problems.append(f"missing host {path}")
    if problems:
        for p in problems:
            print(f"! {p}")
        sys.exit(1)
    print("ok: palette and colours in sync")


def main() -> None:
    if len(sys.argv) != 2 or sys.argv[1] not in {"generate", "apply", "check"}:
        print("usage: gen-colors.py [generate|apply|check]")
        sys.exit(2)
    cmd = sys.argv[1]
    if cmd == "generate":
        generate()
    elif cmd == "apply":
        apply_()
    else:
        check()


if __name__ == "__main__":
    main()
